import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { changelogNotes } from "./client-changelog.mjs";
const root=fileURLToPath(new URL("../",import.meta.url));
const messages=JSON.parse(fs.readFileSync(path.join(root,"clients/locales/messages.json"),"utf8"));
// What's new in this build (我的 → 本版更新): generated from the version's section of clients/CHANGELOG.md, one item
// per line. Every version needs a section in all three languages, so a version bump without notes fails the check.
const version=JSON.parse(fs.readFileSync(path.join(root,"clients/version.json"),"utf8")).version;
messages.whats_new_notes=Object.fromEntries(["zh","en","ru"].map(locale=>{
  const items=changelogItems(changelogNotes(version),locale);
  if(!items.length)throw Error(`clients/CHANGELOG.md: add "## ${version}" with "### ${locale}" items`);
  return [locale,items.join("\n")];
}));
function changelogItems(notes,locale){
  let block="";const items=[];
  for(const line of notes.split("\n")){
    const heading=line.trim().match(/^###\s*([a-z]{2})\s*$/i);
    if(heading){block=heading[1].toLowerCase();continue;}
    const item=line.trim().replace(/^[-*•]\s*/,"");
    if(block===locale&&item)items.push(item);
  }
  return items;
}
const entries=Object.entries(messages).sort(([a],[b])=>a.localeCompare(b));
const placeholders=value=>[...value.matchAll(/\{(\d+)\}/g)].map(m=>m[1]).sort().join(",");
for(const [key,values] of entries) {
  if(!/^[a-z][a-z0-9_]*$/.test(key))throw Error(`Invalid resource key: ${key}`);
  for(const locale of ["en","zh","ru"]) {
    if(!values[locale]?.trim())throw Error(`Missing ${locale}: ${key}`);
    if(placeholders(values[locale])!==placeholders(values.en))throw Error(`Placeholder mismatch: ${locale}/${key}`);
  }
}
function write(relative,text){const file=path.join(root,relative);if(process.argv.includes("--check")){if(!fs.existsSync(file)||fs.readFileSync(file,"utf8")!==text)throw Error(`Outdated generated resource: ${relative}`);}else{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,text);}}
const xml=value=>value.replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll(">","&gt;").replaceAll('"',"&quot;");
for(const [locale,folder] of [["en","values"],["zh","values-zh"],["ru","values-ru"]]) {
  const body=entries.map(([key,v])=>`  <string name="${key}">${xml(v[locale].replaceAll("%","%%").replace(/\{(\d+)\}/g,(_,n)=>`%${Number(n)+1}$s`).replaceAll("\\","\\\\").replaceAll("\n","\\n").replaceAll("'","\\'").replaceAll('"','\\"'))}</string>`).join("\n");
  write(`clients/android/app/src/main/res/${folder}/strings.xml`,`<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/native-locales.mjs. -->\n<resources>\n${body}\n</resources>\n`);
}
const strings=Object.fromEntries(entries.map(([key,v])=>[key,{extractionState:"manual",localizations:Object.fromEntries([["en","en"],["zh","zh-Hans"],["ru","ru"]].map(([source,locale])=>[locale,{stringUnit:{state:"translated",value:v[source].replaceAll("%","%%").replace(/\{(\d+)\}/g,(_,n)=>`%${Number(n)+1}$@`)}}]))}]));
write("clients/apple/Shared/Native.xcstrings",JSON.stringify({sourceLanguage:"en",strings,version:"1.0"},null,2)+"\n");
for(const [locale,suffix] of [["en",""],["zh",".zh"],["ru",".ru"]]) {
  write(`clients/windows/Veilbird/Resources/Native${suffix}.resx`,`<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/native-locales.mjs. -->\n<root>\n  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>\n  <resheader name="version"><value>2.0</value></resheader>\n${entries.map(([key,v])=>`  <data name="${key}" xml:space="preserve"><value>${xml(v[locale])}</value></data>`).join("\n")}\n</root>\n`);
}
console.log(`Native resources: ${entries.length} messages × 3 locales verified.`);
