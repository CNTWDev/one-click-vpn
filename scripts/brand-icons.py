#!/usr/bin/env python3
"""Draws every TrackNothing icon from one pixel mark: the empty set (∅) on a 16×16 grid.

Run from the repository root after changing CELLS: python3 scripts/brand-icons.py (needs Pillow).
Writes the Apple app icons, the Windows .ico, the Android vectors and public/favicon.svg.
The same grid is drawn at runtime by each client (PixelMark in Ui.kt, Design.swift, MainWindow.xaml.cs) and by shared/brand.tsx.
"""
from PIL import Image, ImageDraw

CELLS = [tuple(map(int, p.split(","))) for p in (
    "14,1 5,2 6,2 7,2 8,2 9,2 10,2 13,2 3,3 4,3 11,3 12,3 2,4 11,4 13,4 2,5 10,5 13,5 1,6 9,6 14,6 1,7 8,7 14,7 "
    "1,8 7,8 14,8 1,9 6,9 14,9 2,10 5,10 13,10 2,11 4,11 13,11 3,12 4,12 11,12 12,12 2,13 5,13 6,13 7,13 8,13 9,13 10,13 1,14").split()]
BG, LIME = (17, 25, 18), (183, 220, 104)
APPLE = "clients/apple/App/Assets.xcassets/AppIcon.appiconset"


def path(cell, square, ox, oy):
    f = lambda v: f"{round(v, 3):g}"
    return "".join(f"M{f(ox + x * cell)},{f(oy + y * cell)}h{f(square)}v{f(square)}h-{f(square)}z" for x, y in CELLS)


def mark(img, size, ox, oy, gap=0.14):
    draw, cell = ImageDraw.Draw(img), size / 16
    for x, y in CELLS:
        draw.rectangle([ox + x * cell, oy + y * cell, ox + x * cell + cell * (1 - gap) - 1, oy + y * cell + cell * (1 - gap) - 1], fill=LIME)


def windows_icon(size):
    if size in (16, 32):  # exact pixels: one or two per cell
        img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        draw, c = ImageDraw.Draw(img), size // 16
        draw.rounded_rectangle([0, 0, size - 1, size - 1], radius=size // 5, fill=BG + (255,))
        for x, y in CELLS:
            draw.rectangle([x * c, y * c, x * c + c - 1, y * c + c - 1], fill=LIME)
        return img
    img = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle([0, 0, 1023, 1023], radius=200, fill=BG + (255,))
    mark(img, 768, 128, 128)
    return img.resize((size, size), Image.LANCZOS)


# iOS: full bleed, the system rounds the corners.
ios = Image.new("RGB", (1024, 1024), BG)
mark(ios, 576, 224, 224)
ios.save(f"{APPLE}/AppIcon-1024.png")
# macOS: the rounded tile sits inside the canvas (100…924), as Apple's grid asks.
mac = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
ImageDraw.Draw(mac).rounded_rectangle([100, 100, 923, 923], radius=185, fill=BG + (255,))
mark(mac, 480, 272, 272)
for s in (16, 32, 64, 128, 256, 512, 1024):
    mac.resize((s, s), Image.LANCZOS).save(f"{APPLE}/AppIcon-mac-{s}.png")
sizes = [256, 64, 48, 32, 24, 16]
icons = [windows_icon(s) for s in sizes]
icons[0].save("clients/windows/Veilbird/Assets/Veilbird.ico", sizes=[(s, s) for s in sizes], append_images=icons[1:])

with open("clients/android/app/src/main/res/drawable/ic_mark.xml", "w") as out:
    out.write(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- TrackNothing pixel mark on its dark tile. Generated by scripts/brand-icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="48dp" android:height="48dp" android:viewportWidth="48" android:viewportHeight="48">
  <path android:fillColor="#FF1A231C" android:pathData="M10,0h28a10,10 0,0 1,10 10v28a10,10 0,0 1,-10 10h-28a10,10 0,0 1,-10 -10v-28a10,10 0,0 1,10 -10z"/>
  <path android:fillColor="#FFB7DC68" android:pathData="{path(2.5, 2.15, 4, 4)}"/>
</vector>
""")
with open("clients/android/app/src/main/res/drawable/ic_launcher_foreground.xml", "w") as out:
    out.write(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- TrackNothing pixel mark without its tile, inside the 66dp adaptive-icon safe zone. Generated by scripts/brand-icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <path android:fillColor="#B7DC68" android:pathData="{path(3.6, 3.1, 25.2, 25.2)}"/>
</vector>
""")
with open("public/favicon.svg", "w") as out:
    out.write(f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="14" fill="#111912"/>
  <path fill="#B7DC68" d="{path(3.5, 3, 4, 4)}"/>
</svg>
""")
print("Icons written.")
